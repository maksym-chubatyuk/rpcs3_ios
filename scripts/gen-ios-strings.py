#!/usr/bin/env python3
"""Generates core/localized_strings.inc: the English texts of RPCS3's overlays
(home menu, dialogs, trophies...), taken from the Qt frontend's rpcs3qt/localized_emu.h, which
iOS does not build. Run it again when upstream adds strings.

  scripts/gen-ios-strings.py
"""

import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = (root / "rpcs3" / "rpcs3" / "rpcs3qt" / "localized_emu.h").read_text(encoding="utf-8")
target = root / "core" / "localized_strings.inc"

case = re.compile(r'case localized_string_id::(\w+): return (?:tr\(\s*("(?:[^"\\]|\\.)*")(?:, "[^"]*")?\)|(""))')
lines = ["// Generated by scripts/gen-ios-strings.py from rpcs3qt/localized_emu.h. Do not edit.",
         "// X(id, \"text\"); %0 in a text is replaced with the call's argument."]
count = 0
for line in source.splitlines():
    match = case.search(line)
    if match:
        lines.append(f"X({match.group(1)}, {match.group(2) or match.group(3)})")
        count += 1
    elif "case localized_string_id::" in line:
        sys.exit(f"unrecognised line: {line.strip()}")

target.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{count} strings -> {target}")
